#!/usr/bin/env python3
"""Generate a tiny hand-built Type 1 font for the `SafePdf.Core.Font.Type1` tests (task 6.3).

Standard library only; run with `python3 -I Tests/fonts/gen_type1.py [OUTDIR]`.

Writes, into OUTDIR (default: the directory of this script):
  tiny.t1   the font as embedded in a PDF `/FontFile` stream: clear text, binary eexec
            section, trailer of 512 zeros + `cleartomark`; the lengths are printed
  tiny.pfb  the same font with PFB segment headers (0x80 0x01 / 0x02 / 0x03)
  tiny.pfa  the same font with a hex-encoded eexec section
and prints each file as a hex string, ready to paste into the Lean test literals.

The font (Adobe Type 1 Font Format, 1990): FontMatrix [0.001 0 0 0.001 0 0], an explicit
encoding (32 space, 65 A, 66 B, 67 C) and five charstrings:
  .notdef  0 500 hsbw endchar                          width 500
  space    0 250 hsbw endchar                          width 250
  A        10 600 hsbw + a closed triangle             width 600
  B        20 1300 2 div hsbw + `5 callsubr`           width 650 (exercises div, callsubr)
  C        0 700 hsbw 0 0 0 65 66 seac                 width 700 (accented composite A + B)
Subrs 0-3 are the conventional flex/hint-replacement subroutines, Subr 4 is empty, Subr 5 is
two `rlineto`s and `return`. Everything is deterministic (fixed "random" lead bytes).
"""
import os
import sys

EEXEC_R = 55665
CHARSTRING_R = 4330
C1 = 52845
C2 = 22719


def encrypt(plain, r, lead):
    """Type 1 encryption (spec section 7.1) of `lead + plain`."""
    out = bytearray()
    for p in bytes(lead) + bytes(plain):
        c = p ^ (r >> 8)
        r = ((c + r) * C1 + C2) & 0xFFFF
        out.append(c)
    return bytes(out)


def num(v):
    """Charstring number encoding (spec section 6.2)."""
    if -107 <= v <= 107:
        return bytes([v + 139])
    if 108 <= v <= 1131:
        v -= 108
        return bytes([(v >> 8) + 247, v & 0xFF])
    if -1131 <= v <= -108:
        v = -v - 108
        return bytes([(v >> 8) + 251, v & 0xFF])
    return bytes([255]) + (v & 0xFFFFFFFF).to_bytes(4, "big")


OPS = {
    "hstem": [1], "vstem": [3], "vmoveto": [4], "rlineto": [5], "hlineto": [6],
    "vlineto": [7], "rrcurveto": [8], "closepath": [9], "callsubr": [10], "return": [11],
    "hsbw": [13], "endchar": [14], "rmoveto": [21], "hmoveto": [22], "vhcurveto": [30],
    "hvcurveto": [31], "dotsection": [12, 0], "vstem3": [12, 1], "hstem3": [12, 2],
    "seac": [12, 6], "sbw": [12, 7], "div": [12, 12], "callothersubr": [12, 16],
    "pop": [12, 17], "setcurrentpoint": [12, 33],
}


def charstring(src):
    """Assemble a charstring from a whitespace-separated program."""
    out = bytearray()
    for tok in src.split():
        if tok in OPS:
            out += bytes(OPS[tok])
        else:
            out += num(int(tok))
    return bytes(out)


def cs_encrypted(src):
    return encrypt(charstring(src), CHARSTRING_R, b"\x00\x00\x00\x00")


SUBRS = [
    "3 0 callothersubr pop pop setcurrentpoint return",
    "0 1 callothersubr return",
    "0 2 callothersubr return",
    "return",
    "return",
    "100 0 rlineto 0 100 rlineto return",
]

GLYPHS = [
    (".notdef", "0 500 hsbw endchar"),
    ("space", "0 250 hsbw endchar"),
    ("A", "10 600 hsbw 0 0 rmoveto 300 700 rlineto 300 -700 rlineto closepath endchar"),
    ("B", "20 1300 2 div hsbw 0 0 rmoveto 5 callsubr closepath endchar"),
    ("C", "0 700 hsbw 0 0 0 65 66 seac"),
]

CLEAR = b"""%!PS-AdobeFont-1.0: SafePdfTiny 001.000
%%CreationDate: generated by Tests/fonts/gen_type1.py
11 dict begin
/FontInfo 2 dict dup begin
/Notice (Test font (c) nobody \\(public domain\\)) readonly def
/FullName (SafePdf Tiny) readonly def
end readonly def
/FontName /SafePdfTiny def
/PaintType 0 def
/FontType 1 def
/FontMatrix [0.001 0 0 0.001 0 0] readonly def
/Encoding 256 array
0 1 255 {1 index exch /.notdef put} for
dup 32 /space put
dup 65 /A put
dup 66 /B put
dup 67 /C put
readonly def
/FontBBox {-10 -20 1000 800} readonly def
currentdict end
currentfile eexec
"""


def private_part():
    out = bytearray()
    out += b"dup /Private 8 dict dup begin\n"
    out += b"/RD{string currentfile exch readstring pop}executeonly def\n"
    out += b"/ND{noaccess def}executeonly def\n"
    out += b"/NP{noaccess put}executeonly def\n"
    out += b"/lenIV 4 def\n"
    out += b"/BlueValues [-20 0 700 720] def\n"
    out += b"/MinFeature{16 16}def\n"
    out += b"/password 5839 def\n"
    out += b"/Subrs %d array\n" % len(SUBRS)
    for i, s in enumerate(SUBRS):
        e = cs_encrypted(s)
        out += b"dup %d %d RD " % (i, len(e)) + e + b" NP\n"
    out += b"ND\n"
    out += b"2 index /CharStrings %d dict dup begin\n" % len(GLYPHS)
    for name, s in GLYPHS:
        e = cs_encrypted(s)
        out += b"/%s %d RD " % (name.encode(), len(e)) + e + b" ND\n"
    out += b"end\nend\nreadonly put\nnoaccess put\n"
    out += b"dup /FontName get exch definefont pop\nmark currentfile closefile\n"
    return bytes(out)


TRAILER = (b"0" * 64 + b"\n") * 8 + b"cleartomark\n"


def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
    binary = encrypt(private_part(), EEXEC_R, b"\x5a\x31\xc4\x08")
    t1 = CLEAR + binary + TRAILER
    pfb = (b"\x80\x01" + len(CLEAR).to_bytes(4, "little") + CLEAR
           + b"\x80\x02" + len(binary).to_bytes(4, "little") + binary
           + b"\x80\x01" + len(TRAILER).to_bytes(4, "little") + TRAILER + b"\x80\x03")
    hexed = binary.hex()
    pfa = CLEAR + b"".join(hexed[i:i + 64].encode() + b"\n"
                           for i in range(0, len(hexed), 64)) + TRAILER
    for name, data in (("tiny.t1", t1), ("tiny.pfb", pfb), ("tiny.pfa", pfa)):
        with open(os.path.join(outdir, name), "wb") as f:
            f.write(data)
    print("Length1 %d Length2 %d Length3 %d" % (len(CLEAR), len(binary), len(TRAILER)))
    for name, data in (("t1", t1), ("pfb", pfb), ("pfa", pfa)):
        print("%s (%d bytes, trailer omitted):" % (name, len(data)))
        cut = {"t1": len(CLEAR) + len(binary),
               "pfb": 6 + len(CLEAR) + 6 + len(binary),
               "pfa": len(pfa) - len(TRAILER)}[name]
        print(data[:cut].hex())


if __name__ == "__main__":
    main()
